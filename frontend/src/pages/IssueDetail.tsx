import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { ArrowLeft, Bot, ExternalLink, RefreshCw } from "lucide-react";
import { useState, type FormEvent } from "react";
import { Link, useParams } from "react-router-dom";
import { api, patch, post } from "../api/client";
import type { AISuggestion, AIStatus, IssueDetail } from "../api/types";
import { usePageTitle } from "../components/Layout";
import { Alert, Button, ButtonLink, Card, CodeBlock, ImpactBadge, SelectField, Spinner, StatusBadge, Tag, TextArea } from "../components/ui";
import { CATEGORY_LABELS, formatDate, STATUS_LABEL } from "../lib/format";

function AISuggestionView({ s }: { s: AISuggestion }) {
  return (
    <div className="space-y-3 text-sm">
      <p className="inline-block rounded bg-amber-100 px-2 py-0.5 text-xs font-semibold text-amber-950">AI-generated suggestion – review and test before applying</p>
      <p className="font-medium">{s.summary}</p>
      {s.why_it_matters && <p><strong>Why it matters:</strong> {s.why_it_matters}</p>}
      {s.affected_users.length > 0 && <p><strong>Who is affected:</strong> {s.affected_users.join(", ")}</p>}
      <p><strong>Recommended fix:</strong> {s.recommended_fix}</p>
      {(s.code_before || s.code_after) && (
        <div className="grid gap-3 lg:grid-cols-2">
          {s.code_before && <CodeBlock label="Before (from the scanned page)" code={s.code_before} />}
          {s.code_after && <CodeBlock label="Suggested after (example – adapt to your code)" code={s.code_after} />}
        </div>
      )}
      {s.verification_steps.length > 0 && (
        <div>
          <p className="font-semibold">How to verify</p>
          <ol className="list-decimal pl-5">{s.verification_steps.map((v) => <li key={v}>{v}</li>)}</ol>
        </div>
      )}
      {s.wcag_references.length > 0 && <p><strong>WCAG:</strong> {s.wcag_references.join(", ")}</p>}
      {s.caveats && <p className="text-slate-700"><strong>Caveats:</strong> {s.caveats}</p>}
      <p className="text-xs text-slate-700">Generated by {s.provider} / {s.model}. Not applied to your website automatically.</p>
    </div>
  );
}

export default function IssueDetailPage() {
  const { id = "" } = useParams();
  const qc = useQueryClient();
  const issue = useQuery({ queryKey: ["issue", id], queryFn: () => api<IssueDetail>(`/issues/${id}`) });
  const aiStatus = useQuery({ queryKey: ["ai-status"], queryFn: () => api<AIStatus>("/ai/status") });
  usePageTitle(issue.data?.help ?? "Issue");
  const [status, setStatus] = useState<string | null>(null);
  const [reason, setReason] = useState("");
  const [statusError, setStatusError] = useState<string | null>(null);
  const [note, setNote] = useState("");
  const [saved, setSaved] = useState<string | null>(null);

  const refresh = () => {
    qc.invalidateQueries({ queryKey: ["issue", id] });
    qc.invalidateQueries({ queryKey: ["issues"] });
    qc.invalidateQueries({ queryKey: ["facets"] });
  };
  const updateStatus = useMutation({
    mutationFn: () => patch<IssueDetail>(`/issues/${id}/status`, { status, reason }),
    onSuccess: () => {
      setSaved("Status updated.");
      setReason("");
      setStatus(null);
      refresh();
    },
    onError: (e) => setStatusError((e as Error).message),
  });
  const addNote = useMutation({
    mutationFn: () => post(`/issues/${id}/notes`, { body: note }),
    onSuccess: () => {
      setNote("");
      setSaved("Note added.");
      refresh();
    },
  });
  const ai = useMutation({
    mutationFn: (regen: boolean) => post<AISuggestion>(`/ai/issues/${id}/remediation${regen ? "?refresh=true" : ""}`),
    onSuccess: () => refresh(),
  });

  if (issue.isLoading) return <Spinner />;
  if (issue.error) return <Alert tone="error" title="Issue not found">{(issue.error as Error).message}</Alert>;
  const i = issue.data!;
  const current = status ?? i.status;
  const suggestion = ai.data ?? i.ai_suggestion;

  const submitStatus = (e: FormEvent) => {
    e.preventDefault();
    setStatusError(null);
    setSaved(null);
    if (current === "ignored" && !reason.trim()) {
      setStatusError("Enter a reason for ignoring this issue");
      return;
    }
    updateStatus.mutate();
  };

  return (
    <>
      <Link to={`/scans/${i.scan_id}`} className="mb-4 inline-flex items-center gap-1 text-sm font-medium text-navy-800 underline">
        <ArrowLeft className="h-4 w-4" aria-hidden="true" />Back to scan results
      </Link>
      <div className="mb-6">
        <div className="flex flex-wrap items-center gap-2">
          <ImpactBadge impact={i.impact} />
          <StatusBadge status={i.status} />
          {i.kind === "needs_review" ? <Tag>Needs review – not confirmed</Tag> : <Tag tone="navy">Confirmed violation</Tag>}
          {i.regressed && <Tag>Previously marked fixed – detected again</Tag>}
        </div>
        <h1 className="mt-2 text-2xl font-semibold text-navy-900">{i.help || i.rule_id}</h1>
        <p className="mt-1 text-slate-700">{i.description}</p>
      </div>

      <div className="grid gap-6 xl:grid-cols-3">
        <div className="space-y-6 xl:col-span-2">
          <Card aria-labelledby="where-h">
            <h2 id="where-h" className="mb-3 font-semibold text-navy-900">Where it was found</h2>
            <dl className="grid gap-3 text-sm sm:grid-cols-2">
              <div><dt className="text-slate-700">Page</dt><dd className="break-all">{i.page_url}</dd></div>
              <div><dt className="text-slate-700">CSS selector</dt><dd><code className="break-all">{i.selector}</code></dd></div>
              <div><dt className="text-slate-700">Rule</dt><dd><code>{i.rule_id}</code> · {CATEGORY_LABELS[i.category] ?? i.category}</dd></div>
              <div><dt className="text-slate-700">Detected by</dt><dd>{i.source}</dd></div>
            </dl>
            {i.html_snippet && <div className="mt-4"><CodeBlock label="HTML snippet (as captured)" code={i.html_snippet} /></div>}
            {i.failure_summary && <div className="mt-4"><CodeBlock label="What the engine found" code={i.failure_summary} /></div>}
          </Card>

          <Card aria-labelledby="wcag-h">
            <h2 id="wcag-h" className="mb-3 font-semibold text-navy-900">WCAG mapping</h2>
            {i.wcag_details.length === 0 ? (
              <p className="text-sm text-slate-800">This rule has no WCAG success-criterion mapping in the scanning engine. It is reported as an accessibility <strong>best practice</strong>, not as a WCAG failure.</p>
            ) : (
              <ul className="space-y-1 text-sm">
                {i.wcag_details.map((c) => (
                  <li key={c.number}>
                    <a href={c.url} target="_blank" rel="noopener noreferrer" className="font-medium text-navy-800 underline">
                      {c.number} {c.name}<span className="sr-only"> (opens in a new tab)</span>
                    </a>{" "}
                    – Level {c.level}
                  </li>
                ))}
              </ul>
            )}
            {i.help_url && (
              <a href={i.help_url} target="_blank" rel="noopener noreferrer" className="mt-3 inline-flex items-center gap-1 text-sm font-medium text-navy-800 underline">
                Rule documentation from Deque <ExternalLink className="h-3.5 w-3.5" aria-hidden="true" /><span className="sr-only">(opens in a new tab)</span>
              </a>
            )}
          </Card>

          <Card aria-labelledby="fix-h">
            <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
              <h2 id="fix-h" className="font-semibold text-navy-900">How to fix it</h2>
              <div className="flex gap-2">
                {suggestion ? (
                  <Button size="sm" variant="secondary" disabled={!aiStatus.data?.enabled} loading={ai.isPending} onClick={() => ai.mutate(true)} icon={<RefreshCw className="h-4 w-4" aria-hidden="true" />}>Regenerate AI suggestion</Button>
                ) : (
                  <Button size="sm" disabled={!aiStatus.data?.enabled} loading={ai.isPending} onClick={() => ai.mutate(false)} icon={<Bot className="h-4 w-4" aria-hidden="true" />}>Get AI suggestion</Button>
                )}
                <ButtonLink size="sm" variant="secondary" to={`/assistant?scan=${i.scan_id}&issue=${i.id}`}>Ask a question</ButtonLink>
              </div>
            </div>
            {!aiStatus.data?.enabled && <Alert tone="info" className="mb-3">{aiStatus.data?.message ?? "AI is not configured."}</Alert>}
            {ai.error && <Alert tone="error" live className="mb-3">{(ai.error as Error).message}</Alert>}
            <div aria-live="polite">{suggestion && <AISuggestionView s={suggestion} />}</div>
            {i.guidance && (
              <div className={suggestion ? "mt-6 border-t border-slate-200 pt-4" : undefined}>
                <h3 className="mb-2 font-semibold text-navy-900">Built-in guidance (not AI)</h3>
                <p className="text-sm">{i.guidance.fix}</p>
                <p className="mt-2 text-sm"><strong>Who is affected:</strong> {i.guidance.users.join(", ")}</p>
                <div className="mt-3 grid gap-3 lg:grid-cols-2">
                  <CodeBlock label="Generic example – before" code={i.guidance.before} />
                  <CodeBlock label="Generic example – after" code={i.guidance.after} />
                </div>
              </div>
            )}
            {!suggestion && !i.guidance && aiStatus.data?.enabled === false && (
              <p className="text-sm">See the rule documentation linked above for remediation guidance.</p>
            )}
            <p className="mt-4 text-xs text-slate-700">Examples are suggestions; no single example is correct for every page. Re-scan and test manually after making changes.</p>
          </Card>
        </div>

        <div className="space-y-6">
          <Card aria-labelledby="status-h">
            <h2 id="status-h" className="mb-3 font-semibold text-navy-900">Status</h2>
            <form onSubmit={submitStatus} className="flex flex-col gap-3" noValidate>
              <SelectField label="Status" value={current} onChange={(e) => setStatus(e.target.value)}>
                {["open", "in_progress", "marked_fixed", "ignored"].map((s) => <option key={s} value={s}>{STATUS_LABEL[s]}</option>)}
              </SelectField>
              {(current === "ignored" || current === "marked_fixed") && (
                <TextArea label={current === "ignored" ? "Reason for ignoring" : "Comment (optional)"} required={current === "ignored"} value={reason} onChange={(e) => setReason(e.target.value)} error={statusError ?? undefined} rows={3} />
              )}
              {current === "marked_fixed" && <p className="text-xs text-slate-700">“Marked fixed” is your manual decision. The fix is only confirmed when a later scan no longer detects this issue.</p>}
              <Button type="submit" loading={updateStatus.isPending} disabled={current === i.status && !reason}>Update status</Button>
              {saved && <Alert tone="success" live>{saved}</Alert>}
            </form>
          </Card>

          <Card aria-labelledby="notes-h">
            <h2 id="notes-h" className="mb-3 font-semibold text-navy-900">Internal notes</h2>
            {i.notes.length === 0 ? <p className="mb-3 text-sm text-slate-700">No notes yet.</p> : (
              <ul className="mb-3 space-y-2">
                {i.notes.map((n) => (
                  <li key={n.id} className="rounded-md bg-slate-50 p-2 text-sm">
                    <p className="whitespace-pre-wrap">{n.body}</p>
                    <p className="mt-1 text-xs text-slate-700">{formatDate(n.created_at)}</p>
                  </li>
                ))}
              </ul>
            )}
            <form onSubmit={(e) => { e.preventDefault(); if (note.trim()) addNote.mutate(); }} className="flex flex-col gap-2">
              <TextArea label="Add a note" value={note} onChange={(e) => setNote(e.target.value)} rows={3} />
              <Button type="submit" variant="secondary" loading={addNote.isPending} disabled={!note.trim()}>Add note</Button>
            </form>
          </Card>

          <Card aria-labelledby="history-h">
            <h2 id="history-h" className="mb-3 font-semibold text-navy-900">History</h2>
            {i.history.length === 0 ? <p className="text-sm text-slate-700">No status changes yet.</p> : (
              <ol className="space-y-2 text-sm">
                {i.history.map((h) => (
                  <li key={h.id}>
                    <p><strong>{STATUS_LABEL[h.from_status] ?? (h.from_status || "—")}</strong> → <strong>{STATUS_LABEL[h.to_status] ?? h.to_status}</strong>{!h.actor_id && " (automatic)"}</p>
                    {h.reason && <p className="text-slate-800">{h.reason}</p>}
                    <p className="text-xs text-slate-700">{formatDate(h.created_at)}</p>
                  </li>
                ))}
              </ol>
            )}
          </Card>
        </div>
      </div>
    </>
  );
}
